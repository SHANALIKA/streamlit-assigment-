"""# Model Training"""

import pandas as pd
import numpy as np

from sklearn.model_selection import train_test_split, cross_val_score
from sklearn.preprocessing import StandardScaler
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.svm import SVC
from sklearn.metrics import accuracy_score, classification_report
import joblib

# Binary target: good wine (>=7) vs not
df['quality_label'] = (df['quality'] >= 7).astype(int)

# Features & target
X = df.drop(columns=['quality', 'quality_label'])
y = df['quality_label']

# Standardize features
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

# Train-test split
X_train, X_test, y_train, y_test = train_test_split(
    X_scaled, y, test_size=0.2, random_state=42, stratify=y
)

models = {
    "Random Forest": RandomForestClassifier(random_state=42),
    "Logistic Regression": LogisticRegression(max_iter=1000, random_state=42),
    "SVM": SVC(kernel='rbf', probability=True, random_state=42)
}

cv_results = {}
for name, model in models.items():
    scores = cross_val_score(model, X_train, y_train, cv=5, scoring='accuracy')
    cv_results[name] = scores.mean()
    print(f"{name} CV Accuracy: {scores.mean():.4f} (+/- {scores.std():.4f})")

best_model_name = max(cv_results, key=cv_results.get)
best_model = models[best_model_name]
print(f"\nBest Model: {best_model_name}")

# Train on full training set
best_model.fit(X_train, y_train)

y_pred = best_model.predict(X_test)
print("\nTest Accuracy:", accuracy_score(y_test, y_pred))
print("\nClassification Report:\n", classification_report(y_test, y_pred))

joblib.dump(best_model, f"{best_model_name.replace(' ', '_')}_model.pkl")
print(f"\nModel saved as {best_model_name.replace(' ', '_')}_model.pkl")

# Save the scaler too (important for predictions later)
joblib.dump(scaler, "scaler.pkl")
print("Scaler saved as scaler.pkl")

